  await page.setViewportSize({width:390,height:844})
  const first=page.getByLabel('Première colonne mobile',{exact:true}),second=page.getByLabel('Colonne mobile',{exact:true})
  await expect(second.locator('option')).toHaveText(['Chargé','Coût','Part solaire','Durée'])
  await second.selectOption('cost')
  await expect(page.locator('.sessions-table tbody')).toContainText('1,90 €')
  await expect(page.locator('.sessions-table tfoot')).toContainText('1,90 €')
  await first.selectOption('cost')
  await expect(second).toHaveValue('energy')
